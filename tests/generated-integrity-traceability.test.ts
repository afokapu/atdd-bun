// URN: test:toolkit:generated-integrity-traceability:E001-UNIT-001-bound-test-file
// Acceptance: acc:toolkit:E001-UNIT-001-bound-test-file
// Phase: UNIT
// Layer: integration
import { expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { checkIntegrity } from "../src/integrity";
import { runImplementation } from "../src/enforce";
import { initializeRepository } from "../src/setup";

const packageRoot = resolve(import.meta.dir, "..");
const packageVersion = (await Bun.file(join(packageRoot, "package.json")).json() as { version: string }).version;
const acceptance = "acc:atdd-bun:E001-UNIT-001-enforcement-surfaces-canonical";
const testUrn = "test:atdd-bun:integrity:E001-UNIT-001-enforcement-surfaces-canonical";
const catalogName = "atdd-bun.integrity.acceptance.yaml";
const generatedCatalog = (version = packageVersion) => `# Generated by @afokapu/atdd-bun ${version}. Do not edit; run \`atdd-bun init --replace\`.
# atdd-bun generated integrity catalog
acceptances:
  - identity:
      urn: ${acceptance}
`;

const git = async (root: string, ...args: string[]) => {
  const child = Bun.spawn({ cmd: ["git", ...args], cwd: root, stdout: "pipe", stderr: "pipe" });
  expect(await child.exited).toBe(0);
};

async function consumer(config?: string) {
  const root = await mkdtemp(join(tmpdir(), "atdd-generated-trace-"));
  await git(root, "init", "-q", "-b", "feature");
  await git(root, "config", "user.email", "generated-trace@test");
  await git(root, "config", "user.name", "Generated Trace Test");
  await writeFile(join(root, ".git/info/exclude"), "node_modules/\n");
  await writeFile(join(root, "package.json"), JSON.stringify({
    name: "generated-trace-consumer",
    devDependencies: { "@afokapu/atdd-bun": `^${packageVersion}` },
  }, null, 2));
  await writeFile(join(root, "bun.lock"), `{
  "packages": {
    "@afokapu/atdd-bun": ["@afokapu/atdd-bun@${packageVersion}", "", { "bin": { "atdd-bun": "src/cli.ts" } }, "sha512-red=="]
  }
}
`);
  if (config !== undefined) await writeFile(join(root, "atdd-bun.yaml"), config);
  await mkdir(join(root, "node_modules/@afokapu"), { recursive: true });
  await symlink(packageRoot, join(root, "node_modules/@afokapu/atdd-bun"), "dir");
  expect((await initializeRepository(root)).ok).toBeTrue();
  return root;
}

const generatedFindings = async (root: string) => [
  ...await runImplementation("bun_tester_discipline_detector", { scanRoots: [root], excludes: ["node_modules", ".git", ".atdd"] }),
  ...await runImplementation("atdd_traceability_closure", { scanRoots: [root], excludes: ["node_modules", ".git", ".atdd"] }),
].filter(finding => finding.file.endsWith("atdd-bun.integrity.test.ts"));

const expectGeneratedPair = async (root: string, planRoot: string) => {
  const testPath = join(root, "atdd-bun.integrity.test.ts");
  const catalogRelative = `${planRoot}/${catalogName}`;
  const catalogPath = join(root, catalogRelative);
  const generatedTest = await readFile(testPath, "utf8");
  expect(generatedTest).toContain(`// URN: ${testUrn}`);
  expect(generatedTest).toContain(`// Acceptance: ${acceptance}`);
  expect(generatedTest).toContain("// Phase: UNIT");
  expect(generatedTest).toContain("// Layer: integration");
  expect(generatedTest).toContain(`// atdd-bun integrity catalog: ${catalogRelative}`);
  expect(await Bun.file(catalogPath).exists()).toBeTrue();
  expect(await readFile(catalogPath, "utf8")).toContain(`urn: ${acceptance}`);
  expect(await generatedFindings(root)).toEqual([]);
};

test("supported init generates an identified and resolvably bound integrity pair under the default plan root", async () => {
  const root = await consumer();
  try { await expectGeneratedPair(root, "plan"); }
  finally { await rm(root, { recursive: true, force: true }); }
});

test("the generated integrity catalog follows a configured plan_root", async () => {
  const root = await consumer("profiles: [tester, traceability]\ntopology:\n  plan_root: contracts\n");
  try {
    await expectGeneratedPair(root, "contracts");
    expect(await Bun.file(join(root, "plan", catalogName)).exists()).toBeFalse();
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("integrity reports an edited or missing generated catalog and init restores it", async () => {
  const root = await consumer("profiles: [tester, traceability]\ntopology:\n  plan_root: contracts\n");
  const catalog = join(root, "contracts", catalogName);
  const findings = async () => checkIntegrity({ root, base: "0000000000000000000000000000000000000000", push: false });
  try {
    await writeFile(catalog, `${await readFile(catalog, "utf8")}# consumer edit\n`);
    expect(await findings()).toContainEqual(expect.objectContaining({ file: `contracts/${catalogName}`, detail: expect.stringContaining("stale") }));
    expect((await initializeRepository(root, true)).ok).toBeTrue();
    await rm(catalog);
    expect(await findings()).toContainEqual(expect.objectContaining({ file: `contracts/${catalogName}`, detail: expect.stringContaining("missing") }));
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("plan_root relocation removes only the exact prior marker-owned catalog path", async () => {
  const root = await consumer("profiles: [tester, traceability]\ntopology:\n  plan_root: plan\n");
  const oldCatalog = join(root, "plan", catalogName);
  const unrelatedCatalog = join(root, "consumer-owned", catalogName);
  const unrelatedYaml = join(root, "plan", "consumer-owned.yaml");
  const unrelatedCatalogText = `${generatedCatalog()}consumer: keep-this-same-name-file\n`;
  const unrelatedYamlText = "consumer: keep-this-arbitrary-yaml\n";
  try {
    await mkdir(dirname(oldCatalog), { recursive: true });
    await writeFile(oldCatalog, generatedCatalog());
    const generatedTest = join(root, "atdd-bun.integrity.test.ts");
    await writeFile(generatedTest, `// atdd-bun integrity catalog: plan/${catalogName}\n${await readFile(generatedTest, "utf8")}`);
    await mkdir(dirname(unrelatedCatalog), { recursive: true });
    await writeFile(unrelatedCatalog, unrelatedCatalogText);
    await writeFile(unrelatedYaml, unrelatedYamlText);
    await writeFile(join(root, "atdd-bun.yaml"), "profiles: [tester, traceability]\ntopology:\n  plan_root: contracts\n");

    expect((await initializeRepository(root, true)).ok).toBeTrue();

    expect(await Bun.file(oldCatalog).exists()).toBeFalse();
    expect(await Bun.file(join(root, "contracts", catalogName)).exists()).toBeTrue();
    expect(await readFile(unrelatedCatalog, "utf8")).toBe(unrelatedCatalogText);
    expect(await readFile(unrelatedYaml, "utf8")).toBe(unrelatedYamlText);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("tester walks generated integrity tests without a generated-file exemption", async () => {
  const parser = await readFile(join(packageRoot, "detectors/bun_tester_discipline_detector/test_header.mjs"), "utf8");
  expect(parser).not.toContain("isGeneratedIntegrityTest");
  expect(parser).not.toContain("INTEGRITY_TEMPLATE");
});
